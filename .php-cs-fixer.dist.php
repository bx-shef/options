<?php

declare(strict_types=1);

/**
 * Правила форматирования PHP.
 *
 * Гоняются отдельной целью composer и отдельным шагом CI, а НЕ из build.sh.
 * Сборке хватает php, git и zip, и она обязана отрабатывать в свежем клоне;
 * позови она линтер — и ./build.sh --check перестал бы запускаться без
 * composer install. Поэтому проверок теперь две, и обе обязательные.
 *
 * Набор правил — @PSR12 целиком, решение владельца. С тем, как файлы писались
 * раньше (табы и открывающая скобка на своей строке), он не совпадает, поэтому
 * переход сделан одним механическим проходом отдельным коммитом, а не по файлу
 * за раз: иначе половина дерева жила бы по одному канону, половина по другому,
 * и линтер не отличал бы «ещё не привели» от «сломали».
 *
 * Версия инструмента в composer.json пришпилена ТОЧНО, без «^»: набор @PSR12 у
 * php-cs-fixer пополняется в минорных выпусках, и с «^3.0» CI однажды покраснел
 * бы на коммите, который ничего не менял. Обновление — осознанная правка одной
 * строки, и диф от неё виден отдельно.
 */

$finder = PhpCsFixer\Finder::create()
    ->in(__DIR__)
    ->exclude(['vendor'])
    // Точечные файлы Symfony Finder пропускает по умолчанию, а этот файл —
    // такой же исходник, как остальные, и правила обязан соблюдать сам.
    ->ignoreDotFiles(false)
    ->notName('.php-cs-fixer.cache');

return (new PhpCsFixer\Config())
    ->setRules([
        '@PSR12' => true,
    ])
    ->setFinder($finder);
